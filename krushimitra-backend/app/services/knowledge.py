def band_for(severity_pct: float) -> tuple[str, str]:
    """Map affected-area % onto (level, risk_level)."""
    pct = max(0.0, min(100.0, severity_pct))
    for bound, level in SEVERITY_BANDS:
        if pct <= bound:
            return level, RISK_BY_LEVEL[level]
    return "critical", RISK_BY_LEVEL["critical"]


def action_for(level: str, curable: bool = True) -> str:
    """The Marathi 'what to do now' line for a severity level."""
    table = _ACTION_CURABLE if curable else _ACTION_NOT_CURABLE
    return table.get(level, _ACTION_CURABLE["moderate"])
